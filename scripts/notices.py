#!/usr/bin/env python3
"""Generate portable notices from the exact locked dependencies of release targets."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu", "x86_64-pc-windows-msvc"]
# Exact expressions reviewed for these releases. MIT is selected wherever offered;
# matchit additionally requires BSD-3-Clause; unicode-ident additionally Unicode-3.0.
PERMITTED = {"MIT", "MIT OR Apache-2.0", "Apache-2.0 OR MIT", "MIT/Apache-2.0", "MIT AND BSD-3-Clause", "(MIT OR Apache-2.0) AND Unicode-3.0", "Unlicense OR MIT", "Apache-2.0 OR BSL-1.0", "Apache-2.0"}

def generate():
    packages = {}
    for target in TARGETS:
        metadata = json.loads(subprocess.check_output(["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", target], cwd=ROOT))
        resolved = {node["id"] for node in metadata["resolve"]["nodes"]}
        for package in metadata["packages"]:
            if package["id"] in resolved and package["source"]:
                packages[package["id"]] = package
    output = ["Graffalo Agent Bridge — third-party notices", "Generated by scripts/notices.py from Cargo.lock for the supported release targets.", "Includes build/test dependencies conservatively. No local paths or credentials.", "The Rust standard library is covered by https://www.rust-lang.org/policies/licenses .", ""]
    for package in sorted(packages.values(), key=lambda p: (p["name"], p["version"])):
        expression = package.get("license")
        if expression not in PERMITTED:
            raise SystemExit(f"License needs review: {package['name']} {expression}")
        directory = Path(package["manifest_path"]).parent
        files = sorted(p for p in directory.iterdir() if p.is_file() and p.name.lower().startswith(("license", "licence", "copying", "notice")))
        # Choose MIT when available, retaining additional/cumulative notices.
        has_mit = any("mit" in p.name.lower() for p in files)
        if has_mit:
            files = [p for p in files if "apache" not in p.name.lower() and "boost" not in p.name.lower() and p.name != "COPYING"]
        if not files:
            raise SystemExit(f"Missing license text: {package['name']}")
        selected = "MIT + BSD-3-Clause" if expression == "MIT AND BSD-3-Clause" else "MIT + Unicode-3.0" if "Unicode-3.0" in expression else "MIT" if "MIT" in expression else "Apache-2.0"
        output.extend(["=" * 72, f"{package['name']} {package['version']}", f"https://crates.io/crates/{package['name']}/{package['version']}", f"Declared: {expression}; selected: {selected}", ""])
        for path in files:
            output.extend([f"--- {path.name} ---", path.read_text(encoding="utf-8"), ""])
    return "\n".join(output).replace("\r\n", "\n").rstrip() + "\n"

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    path = ROOT / "THIRD_PARTY_NOTICES.txt"
    if args.check:
        if path.read_text(encoding="utf-8") != result:
            raise SystemExit("Dependency notices changed; run python3 scripts/notices.py")
    else:
        path.write_text(result, encoding="utf-8")
